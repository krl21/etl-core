defmodule ForcedLoad.ConfigTest do
    use ExUnit.Case, async: false

    defmodule Fixture do
        @moduledoc false
        use ForcedLoad.Config

        @impl true
        def app_name, do: :etl_core_test_app

        @impl true
        def business_name, do: "TEST BUSINESS"

        @impl true
        def documentary_type, do: "test_doc_type"

        @impl true
        def unique_id_field, do: :unique_id

        @impl true
        def unique_id_payload_field, do: "uniqueId"

        @impl true
        def last_update_field, do: :last_update

        @impl true
        def last_update_payload_field, do: "lastUpdate"

        @impl true
        def record_queue_path, do: [:amqp, :queue, :record]

        @impl true
        def task_queue_path, do: [:amqp, :queue, :task]

        @impl true
        def bigquery_table_path, do: [:bigquery, :table, :record]
    end

    setup do
        Application.put_env(:etl_core_test_app, :amqp, queue: %{record: "record_queue", task: "task_queue"})
        Application.put_env(:etl_core_test_app, :bigquery, table: %{record: "dataset.record"})

        on_exit(fn ->
            Application.delete_env(:etl_core_test_app, :amqp)
            Application.delete_env(:etl_core_test_app, :bigquery)
        end)
    end

    describe "ForcedLoad.Config.default/1" do
        test "returns the documented defaults for direct-load fields" do
            assert ForcedLoad.Config.default(:postgres_pool) == :postgres_pool
            assert ForcedLoad.Config.default(:postgres_export_batch_size) == 10_000
            assert ForcedLoad.Config.default(:files_path) == "./tmp"
            assert ForcedLoad.Config.default(:queue_stall_timeout) == 5 * 60_000
        end

        test "an unknown key raises KeyError" do
            assert_raise KeyError, fn -> ForcedLoad.Config.default(:not_a_real_key) end
        end
    end

    describe "resolve_config_path/1 (generated by `use ForcedLoad.Config`)" do
        test "nil and [] both resolve to nil" do
            assert Fixture.resolve_config_path(nil) == nil
            assert Fixture.resolve_config_path([]) == nil
        end

        test "resolves a path against the app's own Application env" do
            assert Fixture.resolve_config_path([:amqp, :queue, :record]) == "record_queue"
        end

        test "a missing top-level key resolves to nil, not an error" do
            assert Fixture.resolve_config_path([:nonexistent_key, :x]) == nil
        end
    end

    describe "build_config/1" do
        test "resolves required fields, path-based fields, and applies documented defaults" do
            config = Fixture.build_config()

            assert config.app_name == :etl_core_test_app
            assert config.business_name == "TEST BUSINESS"
            assert config.record_queue == "record_queue"
            assert config.task_queue == "task_queue"
            assert config.bigquery_table == "dataset.record"
            assert config.time_step == 7
            assert config.batch_size == 200
            assert config.includes_record == true
            assert config.includes_task == true
            assert config.bigquery_direct_load == false
            assert config.postgres_pool == :postgres_pool
        end

        test "optional configs that resolve to nil are omitted, not included as nil" do
            config = Fixture.build_config()
            refute Map.has_key?(config, :id_filter)
            refute Map.has_key?(config, :record_filter)
            refute Map.has_key?(config, :webhook_url)
        end

        test "boolean flags are always present even though they default to false" do
            config = Fixture.build_config()
            assert config.skip_elasticsearch == false
            assert config.skip_bigquery == false
        end

        test "overrides win over every computed value" do
            config = Fixture.build_config(%{business_name: "OVERRIDDEN", time_step: 1})
            assert config.business_name == "OVERRIDDEN"
            assert config.time_step == 1
        end
    end

    describe "build_params/2" do
        test "wraps start and end date into a 2-element list" do
            assert Fixture.build_params(~D[2024-01-01], ~D[2024-01-31]) == [~D[2024-01-01], ~D[2024-01-31]]
        end
    end
end
